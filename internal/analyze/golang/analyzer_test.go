// TestGeneratedFile (TC-P5): a Code-generated header before the package
// clause yields no units and no warnings, even though the file parses. The
// same marker after the package clause is an ordinary comment; the units it
// carries arrive with the unit extraction.
func TestGeneratedFile(t *testing.T) {
	res := analyzeFixture(t, "generated"+extGo)
	require.Empty(t, unitNames(res))
	require.Empty(t, res.Warnings)

	const lateMarker = "package app\n\n// Code generated by hand. DO NOT EDIT.\n\n" +
		"type Message struct {\n\tName string\n}\n"
	require.Empty(t, analyzeSource(t, lateMarker).Warnings)
}

