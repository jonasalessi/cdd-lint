// TestUnsupportedExtension (TC-P7) refuses to guess: a Kotlin file, a
// near-miss extension, a path without one and a fixture kept as text are all
// errors naming the path and the extension.
func TestUnsupportedExtension(t *testing.T) {
	a := newTestAnalyzer(t)
	for _, p := range []string{"a.kt", "a.golang", "a", "a.go.txt"} {
		res, err := a.Analyze(context.Background(), p, []byte("package app\n"))
		require.ErrorContains(t, err, p, p)
		require.Empty(t, res.Units, p)
	}
	_, err := a.Analyze(context.Background(), "a.kt", []byte("package app\n"))
	require.ErrorContains(t, err, `".kt"`)
}

// TestUppercaseExtension (TC-P8): the extension test is case-insensitive.
func TestUppercaseExtension(t *testing.T) {
	a := newTestAnalyzer(t)
	for _, p := range []string{"A.GO", "A.Go"} {
		res, err := a.Analyze(context.Background(), p, []byte("package app\n\ntype A struct{}\n"))
		require.NoError(t, err, p)
		require.Empty(t, res.Warnings, p)
	}
}

// TestCanceledContext (TC-P9) stops before parsing instead of running to
// completion.
func TestCanceledContext(t *testing.T) {
	a := newTestAnalyzer(t)
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	res, err := a.Analyze(ctx, "header_only"+extGo, readFixture(t, "header_only"+extGo))
	require.ErrorIs(t, err, context.Canceled)
	require.ErrorContains(t, err, "header_only")
	require.Empty(t, res.Units)
}

// TestAnalyzerHoldsNoResource (TC-P12): go/parser allocates nothing to
// release, so the analyzer is not an io.Closer and the pipeline has nothing
// to close.
func TestAnalyzerHoldsNoResource(t *testing.T) {
	_, ok := NewAnalyzer(analyze.Options{}).(io.Closer)
	assert.False(t, ok, "the Go analyzer must hold no closable resource")
}

// TestReanalyzeIsStable (TC-P12): one analyzer over the same file many
// times, and two analyzers over it, agree — each call builds its own
// token.FileSet, so nothing accumulates between them.
func TestReanalyzeIsStable(t *testing.T) {
	a := newTestAnalyzer(t)
	src := readFixture(t, "header_only"+extGo)
	first, err := a.Analyze(context.Background(), "header_only"+extGo, src)
	require.NoError(t, err)
	for range 200 {
		res, err := a.Analyze(context.Background(), "header_only"+extGo, src)
		require.NoError(t, err)
		require.Equal(t, first, res)
	}
	other, err := newTestAnalyzer(t).Analyze(context.Background(), "header_only"+extGo, src)
	require.NoError(t, err)
	require.Equal(t, first, other)
}
