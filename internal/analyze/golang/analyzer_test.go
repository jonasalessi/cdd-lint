// TestSyntaxError (TC-P1): a file that does not parse is a warning, not a
// failed run. The position is the one go/parser reports for
// `expected ')', found '{'`, pinned literally so a toolchain change shows up
// here.
func TestSyntaxError(t *testing.T) {
	a := newTestAnalyzer(t)
	res, err := a.Analyze(context.Background(), "broken"+extGo, readFixture(t, "broken.go.txt"))
	require.NoError(t, err)
	require.Empty(t, res.Units)
	require.Equal(t, []string{"syntax error at 3:9"}, res.Warnings)
}

// TestSyntaxWarningFallback (TC-P2): every go/parser failure observed so far
// is a scanner.ErrorList whose first error carries a position, so the 1:1
// fallback is unreachable from real Go source and is asserted through the
// helper the analyzer calls.
func TestSyntaxWarningFallback(t *testing.T) {
	noList := errors.New("read source: broken")
	noPosition := scanner.ErrorList{&scanner.Error{Pos: token.Position{}, Msg: "no position"}}
	for name, err := range map[string]error{
		"not an error list":        noList,
		"first error unpositioned": noPosition,
		"empty error list":         scanner.ErrorList{},
	} {
		t.Run(name, func(t *testing.T) {
			require.Equal(t, "syntax error at 1:1", syntaxWarning(err))
		})
	}
}

